-- Run this in Supabase SQL Editor.
-- Then manually promote your own profile to admin using the SQL at the bottom.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  is_admin boolean not null default false,
  created_at timestamptz not null default now()
);
create table if not exists public.services (
  id bigint generated by default as identity primary key,
  title text not null,
  description text not null default '',
  active boolean not null default true,
  created_at timestamptz not null default now()
);
create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  title text not null,
  description text not null default '',
  image_url text,
  project_url text,
  active boolean not null default true,
  created_at timestamptz not null default now()
);
create table if not exists public.inquiries (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  service text not null default '',
  message text not null,
  status text not null default 'new' check (status in ('new','read')),
  created_at timestamptz not null default now()
);
create table if not exists public.site_settings (
  id bigint generated by default as identity primary key,
  setting_key text unique not null,
  setting_value text not null default '',
  updated_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.services enable row level security;
alter table public.projects enable row level security;
alter table public.inquiries enable row level security;
alter table public.site_settings enable row level security;

-- Security-definer helper avoids recursive profile policies.
create or replace function public.is_nextgenhub_admin()
returns boolean language sql stable security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles
    where id = (select auth.uid()) and is_admin = true
  );
$$;

create policy "users read own profile" on public.profiles
for select to authenticated using (id = (select auth.uid()));
create policy "admins manage profiles" on public.profiles
for all to authenticated using (public.is_nextgenhub_admin())
with check (public.is_nextgenhub_admin());

create policy "public read active services" on public.services
for select to anon, authenticated using (active = true);
create policy "admins manage services" on public.services
for all to authenticated using (public.is_nextgenhub_admin())
with check (public.is_nextgenhub_admin());

create policy "public read active projects" on public.projects
for select to anon, authenticated using (active = true);
create policy "admins manage projects" on public.projects
for all to authenticated using (public.is_nextgenhub_admin())
with check (public.is_nextgenhub_admin());

create policy "visitors submit inquiries" on public.inquiries
for insert to anon, authenticated
with check (
  char_length(trim(name)) between 1 and 100
  and char_length(trim(email)) between 3 and 200
  and char_length(trim(message)) between 1 and 3000
  and status = 'new'
);
create policy "admins read inquiries" on public.inquiries
for select to authenticated using (public.is_nextgenhub_admin());
create policy "admins update inquiries" on public.inquiries
for update to authenticated using (public.is_nextgenhub_admin())
with check (public.is_nextgenhub_admin());
create policy "admins delete inquiries" on public.inquiries
for delete to authenticated using (public.is_nextgenhub_admin());

create policy "public read settings" on public.site_settings
for select to anon, authenticated using (true);
create policy "admins manage settings" on public.site_settings
for all to authenticated using (public.is_nextgenhub_admin())
with check (public.is_nextgenhub_admin());

